function deepAssign(target, source) {
  for (const [k, v] of Object.entries(source)) {
    if (v && typeof v === 'object' && !Array.isArray(v)) {
      target[k] = target[k] || {}
      deepAssign(target[k], v)
    } else {
      target[k] = v
    }
  }
}

